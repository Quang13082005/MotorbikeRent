CREATE TABLE IF NOT EXISTS rental_vehicle_changes (
 id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY,
 order_id bigint NOT NULL,
 old_vehicle_id bigint NOT NULL,
 new_vehicle_id bigint NOT NULL,
 type varchar(255) NULL,
 status varchar(255) NULL,
 old_vehicle_name varchar(255) NULL,
 new_vehicle_name varchar(255) NULL,
 old_plate varchar(255) NULL,
 new_plate varchar(255) NULL,
 old_daily_rate int NULL,
 new_daily_rate int NULL,
 old_rental_fee int NULL,
 new_rental_fee int NULL,
 old_delivery_fee int NULL,
 new_delivery_fee int NULL,
 old_total int NULL,
 new_total int NULL,
 old_security_deposit int NULL,
 new_security_deposit int NULL,
 new_deposit_due int NULL,
 paid_before int NULL,
 balance_paid_before int NULL,
 additional_payment int NULL,
 credit_amount int NULL,
 new_pickup_fee int NULL,
 new_return_fee int NULL,
 new_pickup_type varchar(255) NULL,
 new_pickup_address varchar(255) NULL,
 new_return_type varchar(255) NULL,
 new_return_address varchar(255) NULL,
 new_pickup_lat double NULL,
 new_pickup_lng double NULL,
 new_return_lat double NULL,
 new_return_lng double NULL,
 planned_pickup datetime(6) NULL,
 planned_return datetime(6) NULL,
 expires_at datetime(6) NULL,
 created_at datetime(6) NULL,
 processed_at datetime(6) NULL,
 reason varchar(1000) NULL,
 processed_by_staff_id varchar(255) NULL,
 cancelled_by_staff_id varchar(255) NULL,
 refunded_by_staff_id varchar(255) NULL,
 refunded_amount int NULL,
 refunded_at datetime(6) NULL,
 CONSTRAINT fk_change_order FOREIGN KEY (order_id) REFERENCES rental_orders(order_id),
 CONSTRAINT fk_change_old_vehicle FOREIGN KEY (old_vehicle_id) REFERENCES motorbikes(motorbike_id),
 CONSTRAINT fk_change_new_vehicle FOREIGN KEY (new_vehicle_id) REFERENCES motorbikes(motorbike_id),
 INDEX ix_change_hold (new_vehicle_id,status,expires_at,planned_pickup,planned_return),
 INDEX ix_change_order (order_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
